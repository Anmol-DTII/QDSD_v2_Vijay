/**
 * @file self_test.c
 * @brief Power-on known-answer tests for the MCU crypto the core relies on.
 *
 * Vectors generated offline with pyca/cryptography (fixed test key, not used
 * anywhere else). A failure keeps the token in FAULT with the USB gate closed.
 */
